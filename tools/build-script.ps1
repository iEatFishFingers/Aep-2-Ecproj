<#
.SYNOPSIS
  Builds a single self-contained .jsx that EffectCraft can run.

.DESCRIPTION
  EffectCraft scripts cannot include or eval other files, so the importer and its
  data are joined into one script:

  Import mode (default):
    var AE2EC_DATA = <the .ae2ec.json>;  var AE2EC_OPTIONS = {...};  + effectcraft\AE2EC_Import.jsx
    Run the result with effectcraft-cli, or in EffectCraft: File > Scripts > Run Script File...

  Test mode (-Test):
    exporter + importer (wrapped in a function) + tests\roundtrip.jsx

.EXAMPLE
  .\tools\build-script.ps1 -Json "D:\proj\nonmummy.ae2ec.json"
.EXAMPLE
  .\tools\build-script.ps1 -Test
#>
[CmdletBinding(DefaultParameterSetName = 'Import')]
param(
    [Parameter(ParameterSetName = 'Import', Mandatory = $true, Position = 0)]
    [string]$Json,

    [Parameter(ParameterSetName = 'Import')]
    [string]$OptionsJson = '{}',

    [Parameter(ParameterSetName = 'Test', Mandatory = $true)]
    [switch]$Test,

    [Parameter(ParameterSetName = 'Test')]
    [string]$WriteFixture,

    [Parameter(ParameterSetName = 'Test')]
    [switch]$ReturnFixture,

    [string]$Out
)

$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent $PSScriptRoot
$utf8 = New-Object System.Text.UTF8Encoding($false)

function Read-Utf8([string]$path) { [System.IO.File]::ReadAllText($path, $utf8) }
function Js-String([string]$s) { "'" + ($s -replace '\\', '\\' -replace "'", "\'") + "'" }

$importer = Read-Utf8 (Join-Path $repo 'effectcraft/AE2EC_Import.jsx')
$nl = "`n"

if ($Test) {
    $exporter = Read-Utf8 (Join-Path $repo 'ae/AE2EC_Export.jsx')
    $roundtrip = Read-Utf8 (Join-Path $repo 'tests/roundtrip.jsx')
    if (-not $Out) { $Out = Join-Path $repo 'tests/build/roundtrip.combined.jsx' }
    $header = '// GENERATED by tools/build-script.ps1 -Test. Do not edit; edit the source files.' + $nl +
        'var AE2EC_NO_MAIN = true;' + $nl
    if ($ReturnFixture) { $header += 'var AE2EC_RETURN_FIXTURE = true;' + $nl }
    if ($WriteFixture) { $header += 'var AE2EC_WRITE_FIXTURE = ' + (Js-String ($WriteFixture -replace '\\', '/')) + ';' + $nl }
    $text = $header + $exporter + $nl +
        'function AE2EC_RUN_IMPORTER() {' + $nl + $importer + $nl + 'return AE2EC_IMPORT;' + $nl + '}' + $nl +
        $roundtrip
} else {
    $jsonPath = (Resolve-Path -LiteralPath $Json).Path
    $data = Read-Utf8 $jsonPath
    $head = $data.Substring(0, [Math]::Min(400, $data.Length))
    if ($head -notmatch '"format"\s*:\s*"ae2ec"') {
        throw "$jsonPath does not look like an ae2ec export (no ""format"": ""ae2ec"" near the start)."
    }
    # validate the options JSON
    $null = $OptionsJson | ConvertFrom-Json
    if (-not $Out) {
        $base = $jsonPath -replace '\.json$', '' -replace '\.ae2ec$', ''
        $Out = "$base.ae2ec-import.jsx"
    }
    $text = '// GENERATED by tools/build-script.ps1 from ' + (Split-Path -Leaf $jsonPath) + $nl +
        'var AE2EC_OPTIONS = ' + $OptionsJson + ';' + $nl +
        'var AE2EC_DATA = ' + $data.Trim() + ';' + $nl +
        $importer
}

$outDir = Split-Path -Parent $Out
if ($outDir -and -not (Test-Path -LiteralPath $outDir)) { New-Item -ItemType Directory -Path $outDir -Force | Out-Null }
[System.IO.File]::WriteAllText($Out, $text, $utf8)
Write-Host "Built $Out ($([Math]::Round($text.Length / 1024)) KB)"
$Out
